const dirs: string[] = [];
const identityQuery = `SELECT json_build_object('data_directory',current_setting('data_directory'),'server_version_num',current_setting('server_version_num')::int,'port',current_setting('port')::int,'database',current_database(),'role',current_user,'system_identifier',(SELECT system_identifier::text FROM pg_control_system()),'listen_addresses',current_setting('listen_addresses'),'socket_directories',current_setting('unix_socket_directories'),'config_file',current_setting('config_file'),'hba_file',current_setting('hba_file'),'password_encryption',current_setting('password_encryption'))::text AS identity`;
const extensionsQuery = `SELECT COALESCE(json_agg(extname ORDER BY extname),'[]'::json)::text FROM pg_extension WHERE extname IN ('pg_trgm','pgcrypto','vector')`;
const vectorQuery = `SELECT '[1,2,3]'::vector <-> '[1,2,3]'::vector`;
const nativeConf = '# PostgreSQL initdb config\n';
const nativeHba = 'local all all trust\n';
const nativeAuto = '# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n';

function fakeRuntime(configDir: string) {
  let running = false;
  let database = false;
  let extensions = false;
  let data = join(configDir, 'postgres/17/data');
  let identity: Record<string, unknown> = {};
  const calls: string[] = [];
  const ok = (stdout = '') => ({ code: 0, stdout: Buffer.from(stdout), stderr: Buffer.alloc(0), timedOut: false, truncated: false });
  const fail = (stdout = '') => ({ code: 1, stdout: Buffer.from(stdout), stderr: Buffer.from('private fake failure'), timedOut: false, truncated: false });
  const runner: ProcessRunner = async (file, args) => {
    const binary = file.split('/').pop()!;
    calls.push(`${binary} ${args.join(' ')}`);
    if (binary === 'brew') {
      if (args.join(' ') === '--prefix') return ok('/opt/homebrew');
      if (args.join(' ') === '--prefix postgresql@17') return ok('/opt/homebrew/opt/postgresql@17');
      if (args.join(' ') === '--prefix pgvector') return ok('/opt/homebrew/opt/pgvector');
      if (args.join(' ') === 'list --versions postgresql@17') return ok('postgresql@17 17.5');
      if (args.join(' ') === 'list --versions pgvector') return ok('pgvector 0.8.0');
      return ok();
    }
    if (binary === 'lipo') return ok('arm64');
    if (binary === 'pg_config') {
      if (args[0] === '--version') return ok('PostgreSQL 17.5');
      if (args[0] === '--sharedir') return ok('/opt/homebrew/opt/postgresql@17/share');
      if (args[0] === '--pkglibdir') return ok('/opt/homebrew/opt/pgvector/lib/postgresql@17');
    }
    if (args[0] === '--version') return ok(`${binary} (PostgreSQL) 17.5`);
    if (binary === 'pg_controldata') return ok('Database system identifier: 123456789\n');
    if (binary === 'initdb') {
      data = args[args.indexOf('-D') + 1]!;
      mkdirSync(join(data, 'global'), { recursive: true, mode: 0o700 });
      mkdirSync(join(data, 'pg_wal'), { recursive: true, mode: 0o700 });
      mkdirSync(join(data, 'pg_tblspc'), { recursive: true, mode: 0o700 });
      writeFileSync(join(data, 'PG_VERSION'), '17\n', { mode: 0o600 });
      writeFileSync(join(data, 'global/pg_control'), 'fake control', { mode: 0o600 });
      writeFileSync(join(data, 'postgresql.conf'), nativeConf, { mode: 0o600 });
      writeFileSync(join(data, 'pg_hba.conf'), nativeHba, { mode: 0o600 });
      writeFileSync(join(data, 'postgresql.auto.conf'), nativeAuto, { mode: 0o600 });
      return ok();
    }
    if (binary === 'pg_ctl') {
      if (args.includes('status')) return running ? ok('server running') : { ...fail('no server running'), code: 3 };
      if (args.includes('start')) {
        const owner = JSON.parse(readFileSync(join(configDir, 'postgres/17/owner.json'), 'utf8'));
        identity = {
          data_directory: owner.dataPath, server_version_num: 170005, port: owner.port,
          database: 'postgres', role: 'gbrain', system_identifier: '123456789', listen_addresses: '127.0.0.1',
          socket_directories: owner.socketPath, config_file: join(owner.dataPath, 'postgresql.conf'),
          hba_file: join(owner.dataPath, 'pg_hba.conf'), password_encryption: 'scram-sha-256',
        };
        running = true;
        return ok();
      }
      if (args.includes('stop')) { running = false; return ok(); }
    }
    if (binary === 'createdb') { database = true; return ok(); }
    if (binary === 'psql') {
      const sql = args[args.indexOf('--command') + 1] ?? '';
      if (sql === identityQuery || sql.includes('json_build_object')) return ok(JSON.stringify(identity));
      if (sql === "SELECT 1 FROM pg_database WHERE datname='gbrain'") return ok(database ? '1\n' : '');
      if (sql === 'CREATE EXTENSION IF NOT EXISTS vector; CREATE EXTENSION IF NOT EXISTS pg_trgm; CREATE EXTENSION IF NOT EXISTS pgcrypto;') { extensions = true; return ok(); }
      if (sql === extensionsQuery) return ok(JSON.stringify(extensions ? ['pg_trgm', 'pgcrypto', 'vector'] : []));
      if (sql === vectorQuery) return ok('0\n');
      throw new Error(`Unexpected fake query: ${sql}`);
    }
    throw new Error(`Unexpected fake command: ${file} ${args.join(' ')}`);
  };
  return {
    calls, runner,
    packageDeps: {
      brew: '/brew/brew', executable: () => true, fileExists: () => true,
      listFiles: () => ['vector--0.8.0.sql'], realpath: (path: string) => path,
      lstat: () => ({ isFile: () => true, isSymbolicLink: () => false }),
    },
    portInUse: async () => false,
    allocatePort: () => 55432,
  };
}

function tree(path: string, ignoreLifecycleLock = false): string {
  if (!existsSync(path)) return '<absent>';
  const rows: string[] = [];
  const walk = (dir: string) => { for (const name of readdirSync(dir).sort()) {
    if (ignoreLifecycleLock && dir === path && name === '.lifecycle.lock') continue;
    const full = join(dir, name), stat = lstatSync(full);
    rows.push(`${name}:${stat.mode & 0o777}:${stat.isDirectory() ? 'dir' : readFileSync(full).toString('base64')}`);
    if (stat.isDirectory()) walk(full);
  } };
  walk(path);
  return rows.join('\n');
}

afterEach(() => { for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true }); });

describe('managed-init A↔B composition', () => {
  test('accepts B provision artifacts, command recheck under lock, then published resume', async () => {
    const temp = mkdtempSync(join(tmpdir(), 'gbrain-init-ab-'));
    dirs.push(temp);
    const configDir = join(temp, '.gbrain');
    mkdirSync(configDir, { mode: 0o700 });
    const uid = process.getuid?.() ?? 1000;
    const fake = fakeRuntime(configDir);
    const context = {
      configDir, platform: 'darwin' as const, arch: 'arm64', uid,
      ...fake,
    } as never;
    const artifactPaths = [join(configDir, 'brain.pglite'), join(configDir, 'pglite')];
    const checkInput = { configDir, root: join(configDir, 'postgres/17'), uid, acceptedEnvironmentUrl: false, canonicalPgliteArtifactPaths: artifactPaths };
    let reference: ManagedPostgresReference | undefined;
    await withProvisionedManagedCluster(context, (callbackReference) => { reference = callbackReference; });
    expect(reference).toBeDefined();
    expect(inspectManagedInitPreflight(checkInput)).toMatchObject({ kind: 'owned-resume', phase: 'provisioned', evidence: 'structural-only' });

    const root = join(configDir, 'postgres/17');
    const beforeResume = tree(root);
    let checkedUnderLock = false;
    await withProvisionedManagedCluster(context, (callbackReference) => {
      expect(callbackReference).toEqual(reference!);
      expect(existsSync(join(root, '.lifecycle.lock'))).toBe(true);
      publishManagedInitConfigForInitFile(callbackReference!, configDir, join(configDir, 'config.json'), { embedding_disabled: true });
    }, {}, { beforeMutation(state) {
      expect(state.kind).toBe('owned-resume');
      expect(existsSync(join(root, '.lifecycle.lock'))).toBe(true);
      expect(tree(root, true)).toBe(beforeResume);
      expect(inspectManagedInitCommandEligibility({ configDir, uid, acceptedEnvironmentUrl: false, canonicalPgliteArtifactPaths: artifactPaths })).toEqual({ kind: 'unpublished' });
      checkedUnderLock = true;
    } });
    expect(checkedUnderLock).toBe(true);
    expect(JSON.parse(readFileSync(join(configDir, 'config.json'), 'utf8')).embedding_disabled).toBe(true);
    expect(inspectManagedInitPreflight(checkInput)).toMatchObject({ kind: 'published-resume', phase: 'provisioned', evidence: 'structural-only' });
  });
});
