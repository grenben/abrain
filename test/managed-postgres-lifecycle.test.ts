function configLiteral(value: string): string { return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`; }
function managedConfig(owner: { port: number; socketPath: string; dataPath: string; rootPath: string }): string {
  const hba = join(owner.dataPath, 'pg_hba.conf');
  return [
    "listen_addresses = '127.0.0.1'", `port = ${owner.port}`, `unix_socket_directories = ${configLiteral(owner.socketPath)}`,
    'unix_socket_permissions = 0700', "password_encryption = 'scram-sha-256'", `hba_file = ${configLiteral(hba)}`,
    'logging_collector = on', `log_directory = ${configLiteral(join(owner.rootPath, 'log'))}`, "log_filename = 'postgresql.log'", 'log_file_mode = 0600', 'ssl = off', 'max_connections = 20', '',
  ].join('\n');
}
