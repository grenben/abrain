import { closeSync, constants, fchmodSync, fsyncSync, lstatSync, mkdirSync, openSync, readFileSync, realpathSync, renameSync, writeFileSync, unlinkSync, rmdirSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { createHash, randomUUID } from 'node:crypto';

export const MANAGER_ID = 'gbrain-managed-postgres';
export const FORMAT_VERSION = 1;
export type SetupPhase = 'allocated' | 'initialized' | 'provisioned';
export interface OwnerMetadata {
  formatVersion: number; managerId: string; clusterId: string; uid: number;
  configPath: string; rootPath: string; dataPath: string; pgMajor: 17;
  binaryPrefix: string; binaryVersion: string; pgvectorVersion: string; systemIdentifier: string | null;
  database: string; role: string; socketPath: string; port: number; phase: SetupPhase; controller: 'manual';
  lastFailure?: 'startup_failure';
}
export interface ManagedPaths { configDir: string; root: string; data: string; socket: string; log: string; owner: string; credentials: string; lock: string; receipt: string; }
export interface InitializationReceipt {
  formatVersion: 1; managerId: string; clusterId: string; uid: number; dataPath: string; pgMajor: 17; systemIdentifier: string;
  sha256: { postgresqlConf: string; pgHbaConf: string; postgresqlAutoConf: string };
}
export const NATIVE_POSTGRES_AUTO_CONF = '# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n';
export function canonicalPath(path: string): string {
  const absolute = resolve(path);
  try { return realpathSync(absolute); } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== 'ENOENT') throw e;
    const parent = dirname(absolute);
    if (parent === absolute) throw e;
    return join(canonicalPath(parent), basename(absolute));
  }
}
export function managedPaths(configDir: string, root?: string): ManagedPaths {
  const canonicalConfig = canonicalPath(configDir);
  const requestedRoot = resolve(root ?? join(canonicalConfig, 'postgres', '17'));
  const canonicalRoot = canonicalPath(requestedRoot);
  if (!isAbsolute(canonicalConfig) || !isAbsolute(canonicalRoot) || !inside(canonicalRoot, canonicalConfig)) throw new Error('Managed PostgreSQL root must remain beneath the configured GBrain home.');
  if (inside(requestedRoot, canonicalConfig)) {
    let cursor = dirname(requestedRoot);
    while (inside(cursor, canonicalConfig)) {
      try { if (lstatSync(cursor).isSymbolicLink()) throw new Error('Managed PostgreSQL root ancestry contains a symlink.'); }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
      if (cursor === canonicalConfig) break;
      cursor = dirname(cursor);
    }
    try { if (lstatSync(requestedRoot).isSymbolicLink()) throw new Error('Managed PostgreSQL root ancestry contains a symlink.'); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  }
  return { configDir: canonicalConfig, root: canonicalRoot, data: join(canonicalRoot, 'data'), socket: join(canonicalRoot, 'socket'), log: join(canonicalRoot, 'log'), owner: join(canonicalRoot, 'owner.json'), credentials: join(canonicalRoot, 'credentials.json'), lock: join(canonicalRoot, '.lifecycle.lock'), receipt: join(canonicalRoot, 'init-receipt.json') };
}
function inside(path: string, parent: string): boolean { const r = relative(parent, path); return r === '' || (!r.startsWith(`..${sep}`) && r !== '..' && !isAbsolute(r)); }
export function ensurePrivateDir(path: string, uid = process.getuid?.() ?? -1): void {
  mkdirSync(path, { recursive: true, mode: 0o700 });
  const st = lstatSync(path);
  if (st.isSymbolicLink() || (st.mode & 0o777) !== 0o700 || st.uid !== uid) throw new Error('Managed PostgreSQL directory ownership or permissions are unsafe.');
}
export function validateExistingManagedAncestry(paths: ManagedPaths, uid: number, requestedConfigDir = paths.configDir): void {
  const requested = resolve(requestedConfigDir);
  try {
    const requestedStat = lstatSync(requested);
    if (!requestedStat.isDirectory() || requestedStat.isSymbolicLink() || realpathSync(requested) !== paths.configDir) throw new Error('Managed PostgreSQL configured home is unsafe.');
  } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  const chain: string[] = [];
  let current = paths.root;
  while (current !== paths.configDir) {
    chain.push(current);
    const parent = dirname(current);
    if (parent === current || !inside(parent, paths.configDir)) throw new Error('Managed PostgreSQL ancestry escaped its configured home.');
    current = parent;
  }
  chain.push(paths.configDir);
  for (const path of chain.reverse()) {
    let stat;
    try { stat = lstatSync(path); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') continue; throw error; }
    if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== uid || (stat.mode & 0o022) !== 0) throw new Error('Managed PostgreSQL directory ancestry is unsafe.');
    if (path !== paths.configDir && (stat.mode & 0o777) !== 0o700) throw new Error('Managed PostgreSQL directory ownership or permissions are unsafe.');
  }
  for (const path of [paths.data, paths.log, paths.socket]) {
    try {
      const stat = lstatSync(path);
      if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== uid || (stat.mode & 0o777) !== 0o700) throw new Error('Managed PostgreSQL directory ownership or permissions are unsafe.');
    } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  }
}
export function validateManagedDirectories(paths: ManagedPaths, socketPath: string, uid: number, requestedConfigDir = paths.configDir): void {
  validateExistingManagedAncestry(paths, uid, requestedConfigDir);
  for (const path of [paths.root, paths.data, paths.log, socketPath]) {
    const stat = lstatSync(path);
    if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== uid || (stat.mode & 0o777) !== 0o700 || canonicalPath(path) !== path) throw new Error('Managed PostgreSQL directory ownership or permissions are unsafe.');
  }
  if (!inside(socketPath, paths.root)) {
    const marker = join(socketPath, '.gbrain-managed-owner'), stat = lstatSync(marker);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.uid !== uid || (stat.mode & 0o777) !== 0o600) throw new Error('Managed PostgreSQL runtime socket ownership is unknown.');
  }
}
export function createOwner(paths: ManagedPaths, uid: number, prefix: string, version: string, vectorVersion: string, port: number, clusterId: string = randomUUID()): OwnerMetadata {
  if (!/^[0-9a-f-]{36}$/i.test(clusterId)) throw new Error('Managed PostgreSQL cluster identifier is invalid.');
  return { formatVersion: FORMAT_VERSION, managerId: MANAGER_ID, clusterId, uid, configPath: paths.configDir, rootPath: paths.root, dataPath: paths.data, pgMajor: 17, binaryPrefix: prefix, binaryVersion: version, pgvectorVersion: vectorVersion, systemIdentifier: null, database: 'gbrain', role: 'gbrain', socketPath: paths.socket, port, phase: 'allocated', controller: 'manual' };
}
export function writeOwner(paths: ManagedPaths, owner: OwnerMetadata): void {
  const parent = lstatSync(paths.root);
  if (!parent.isDirectory() || parent.isSymbolicLink() || parent.uid !== owner.uid || (parent.mode & 0o777) !== 0o700) throw new Error('Managed PostgreSQL metadata directory is unsafe.');
  try {
    const existing = lstatSync(paths.owner);
    if (!existing.isFile() || existing.isSymbolicLink() || existing.uid !== owner.uid || (existing.mode & 0o777) !== 0o600) throw new Error('Managed PostgreSQL ownership metadata is unsafe.');
  } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  const temporary = join(paths.root, `.owner.json.tmp-${randomUUID()}`);
  let fd: number | undefined, tempCreated = false, renamed = false;
  try {
    fd = openSync(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0), 0o600);
    tempCreated = true;
    fchmodSync(fd, 0o600);
    writeFileSync(fd, JSON.stringify(owner));
    fsyncSync(fd);
    closeSync(fd); fd = undefined;
    renameSync(temporary, paths.owner); renamed = true;
    let dirFd: number | undefined;
    try { dirFd = openSync(paths.root, constants.O_RDONLY); fsyncSync(dirFd); }
    catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (!['EINVAL', 'ENOTSUP', 'EOPNOTSUPP', 'EISDIR'].includes(code ?? '')) throw error;
    } finally { if (dirFd !== undefined) closeSync(dirFd); }
  } finally {
    if (fd !== undefined) closeSync(fd);
    if (tempCreated && !renamed) { try { unlinkSync(temporary); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; } }
  }
}
/** Durable same-directory replacement for owner-controlled cluster configuration. */
export function atomicWriteOwnedFile(path: string, data: string, uid: number, allowedExisting: (contents: string) => boolean): void {
  try {
    const stat = lstatSync(path);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.uid !== uid || (stat.mode & 0o777) !== 0o600 || !allowedExisting(readFileSync(path, 'utf8'))) throw new Error('Managed PostgreSQL configuration file is unsafe or unknown.');
  } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  const parent = dirname(path), temporary = join(parent, `.${basename(path)}.tmp-${randomUUID()}`);
  let fd: number | undefined, created = false, renamed = false;
  try {
    fd = openSync(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0), 0o600); created = true;
    fchmodSync(fd, 0o600); writeFileSync(fd, data); fsyncSync(fd); closeSync(fd); fd = undefined;
    renameSync(temporary, path); renamed = true;
    let dirFd: number | undefined;
    try { dirFd = openSync(parent, constants.O_RDONLY); fsyncSync(dirFd); }
    catch (error) { if (!['EINVAL', 'ENOTSUP', 'EOPNOTSUPP', 'EISDIR'].includes((error as NodeJS.ErrnoException).code ?? '')) throw error; }
    finally { if (dirFd !== undefined) closeSync(dirFd); }
  } finally {
    if (fd !== undefined) closeSync(fd);
    if (created && !renamed) { try { unlinkSync(temporary); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; } }
  }
}
function readPrivateBytes(path: string, uid: number): Buffer {
  const stat = lstatSync(path);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.uid !== uid || (stat.mode & 0o777) !== 0o600) throw new Error('Managed PostgreSQL file ownership or permissions are unsafe.');
  return readFileSync(path);
}
function sha256(bytes: Buffer): string { return createHash('sha256').update(bytes).digest('hex'); }
export function captureInitializationReceipt(paths: ManagedPaths, owner: OwnerMetadata, uid: number, systemIdentifier: string): InitializationReceipt {
  const conf = readPrivateBytes(join(paths.data, 'postgresql.conf'), uid);
  const hba = readPrivateBytes(join(paths.data, 'pg_hba.conf'), uid);
  const auto = readPrivateBytes(join(paths.data, 'postgresql.auto.conf'), uid);
  if (!auto.equals(Buffer.from(NATIVE_POSTGRES_AUTO_CONF))) throw new Error('Managed PostgreSQL native automatic configuration is unknown.');
  return {
    formatVersion: 1, managerId: MANAGER_ID, clusterId: owner.clusterId, uid, dataPath: paths.data, pgMajor: 17, systemIdentifier,
    sha256: { postgresqlConf: sha256(conf), pgHbaConf: sha256(hba), postgresqlAutoConf: sha256(auto) },
  };
}
export function writeInitializationReceipt(paths: ManagedPaths, receipt: InitializationReceipt): void {
  atomicWriteOwnedFile(paths.receipt, JSON.stringify(receipt), receipt.uid, () => false);
}
export function readInitializationReceipt(paths: ManagedPaths, owner: OwnerMetadata, uid: number): InitializationReceipt {
  let receipt: InitializationReceipt;
  try { receipt = JSON.parse(readPrivateBytes(paths.receipt, uid).toString('utf8')) as InitializationReceipt; }
  catch { throw new Error('Managed PostgreSQL initialization receipt is missing or malformed.'); }
  const hashes = receipt?.sha256;
  if (!receipt || receipt.formatVersion !== 1 || receipt.managerId !== MANAGER_ID || receipt.clusterId !== owner.clusterId || receipt.uid !== uid || receipt.dataPath !== paths.data || receipt.pgMajor !== 17 || !/^\d+$/.test(receipt.systemIdentifier) || (owner.systemIdentifier !== null && owner.systemIdentifier !== receipt.systemIdentifier) || !hashes || !/^[a-f0-9]{64}$/.test(hashes.postgresqlConf) || !/^[a-f0-9]{64}$/.test(hashes.pgHbaConf) || !/^[a-f0-9]{64}$/.test(hashes.postgresqlAutoConf)) throw new Error('Managed PostgreSQL initialization receipt does not match this cluster.');
  return receipt;
}
export function matchesInitializationOrManaged(path: string, uid: number, hash: string, managed: string, allowMissing = false): boolean {
  let bytes: Buffer;
  try { bytes = readPrivateBytes(path, uid); }
  catch (error) { if (allowMissing && (error as NodeJS.ErrnoException).code === 'ENOENT') return true; throw error; }
  return sha256(bytes) === hash || bytes.equals(Buffer.from(managed));
}
export function readOwner(paths: ManagedPaths, uid: number): OwnerMetadata {
  const st = lstatSync(paths.owner);
  if (st.isSymbolicLink() || st.uid !== uid || (st.mode & 0o777) !== 0o600) throw new Error('Managed PostgreSQL ownership metadata is unsafe.');
  let owner: OwnerMetadata;
  try { owner = JSON.parse(readFileSync(paths.owner, 'utf8')); } catch { throw new Error('Managed PostgreSQL ownership metadata is malformed.'); }
  if (!owner || owner.formatVersion !== FORMAT_VERSION || owner.managerId !== MANAGER_ID || !/^[0-9a-f-]{36}$/i.test(owner.clusterId) || owner.uid !== uid || owner.configPath !== paths.configDir || owner.rootPath !== paths.root || owner.dataPath !== paths.data || owner.pgMajor !== 17 || owner.controller !== 'manual' || !['allocated', 'initialized', 'provisioned'].includes(owner.phase) || !Number.isInteger(owner.port) || owner.port < 1024 || [5432, 5434, 6543].includes(owner.port) || !isAbsolute(owner.binaryPrefix) || typeof owner.binaryVersion !== 'string' || typeof owner.pgvectorVersion !== 'string' || !Number.isInteger(owner.uid) || owner.database !== 'gbrain' || owner.role !== 'gbrain' || !isAbsolute(owner.socketPath) || (owner.systemIdentifier !== null && !/^\d+$/.test(owner.systemIdentifier)) || (owner.phase !== 'allocated' && !owner.systemIdentifier)) throw new Error('Managed PostgreSQL ownership metadata does not match this installation.');
  if (owner.lastFailure !== undefined && owner.lastFailure !== 'startup_failure') throw new Error('Managed PostgreSQL ownership metadata has an unknown failure marker.');
  if (canonicalPath(owner.rootPath) !== paths.root || canonicalPath(owner.dataPath) !== paths.data) throw new Error('Managed PostgreSQL ownership paths escaped their private root.');
  validateManagedDirectories(paths, owner.socketPath, uid);
  const socket = lstatSync(owner.socketPath);
  if (!socket.isDirectory() || socket.isSymbolicLink() || socket.uid !== uid || (socket.mode & 0o777) !== 0o700 || canonicalPath(owner.socketPath) !== owner.socketPath || Buffer.byteLength(join(owner.socketPath, `.s.PGSQL.${owner.port}`)) > 103) throw new Error('Managed PostgreSQL socket directory is unsafe or too long.');
  if (!inside(owner.socketPath, paths.root)) {
    const markerPath = join(owner.socketPath, '.gbrain-managed-owner'), marker = lstatSync(markerPath);
    if (!marker.isFile() || marker.isSymbolicLink() || marker.uid !== uid || (marker.mode & 0o777) !== 0o600 || readFileSync(markerPath, 'utf8') !== `${MANAGER_ID}:${owner.clusterId}:${uid}`) throw new Error('Managed PostgreSQL runtime socket ownership is unknown.');
  }
  return owner;
}

export function assertPrivateFile(path: string, uid: number, expected?: string): void {
  const st = lstatSync(path);
  if (!st.isFile() || st.isSymbolicLink() || st.uid !== uid || (st.mode & 0o777) !== 0o600 || (expected !== undefined && readFileSync(path, 'utf8') !== expected)) throw new Error('Managed PostgreSQL file ownership or permissions are unsafe.');
}

export function readCredentials(paths: ManagedPaths, uid: number): { password: string } {
  const st = lstatSync(paths.credentials);
  if (!st.isFile() || st.isSymbolicLink() || st.uid !== uid || (st.mode & 0o777) !== 0o600) throw new Error('Managed PostgreSQL credentials are missing or unsafe.');
  try {
    const value = JSON.parse(readFileSync(paths.credentials, 'utf8')) as { password?: unknown };
    if (typeof value.password !== 'string' || value.password.length < 32) throw new Error();
    return { password: value.password };
  } catch { throw new Error('Managed PostgreSQL credentials are missing or malformed.'); }
}
/** Exclusive lock creation is fail-closed; an extant lock is never stolen based on PID/mtime. */
export function acquireLifecycleLock(paths: ManagedPaths): () => void {
  try { mkdirSync(paths.lock, { mode: 0o700 }); }
  catch { throw new Error('Managed PostgreSQL lifecycle is locked or lock state is ambiguous; no action was taken.'); }
  const token = randomUUID(), lockOwner = join(paths.lock, 'owner');
  try { writeFileSync(lockOwner, `${process.pid}:${token}`, { mode: 0o600, flag: 'wx' }); }
  catch { throw new Error('Managed PostgreSQL lifecycle lock state is ambiguous; no action was taken.'); }
  return () => {
    try { if (readFileSync(lockOwner, 'utf8') !== `${process.pid}:${token}`) return; unlinkSync(lockOwner); rmdirSync(paths.lock); } catch { /* preserve ambiguous lock state */ }
  };
}
